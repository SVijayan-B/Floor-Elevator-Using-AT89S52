#include <reg52.h>


/* =================================================
   L293D MOTOR CONNECTION

   P3.2 -> L293D IN1 -> AT89S52 Pin 12
   P3.3 -> L293D IN2 -> AT89S52 Pin 13

   ================================================= */

sbit MOTOR_IN1 = P3^2;
sbit MOTOR_IN2 = P3^3;


/* =================================================
   MOTOR UP
   ================================================= */

void motor_up(void)
{
    MOTOR_IN1 = 1;
    MOTOR_IN2 = 0;
}


/* =================================================
   MOTOR DOWN
   ================================================= */

void motor_down(void)
{
    MOTOR_IN1 = 0;
    MOTOR_IN2 = 1;
}


/* =================================================
   MOTOR STOP
   ================================================= */

void motor_stop(void)
{
    MOTOR_IN1 = 0;
    MOTOR_IN2 = 0;
}